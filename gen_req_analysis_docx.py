def P(text="", bold=False, size=10.5, color=None, align=None, italic=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold; r.italic = italic; r.font.size = Pt(size)
    if color: r.font.color.rgb = color
    set_cjk_run(r)
    if align: p.alignment = align
    return p

def set_cjk_run(r):
    r.font.name = "Microsoft YaHei"
    r._element.rPr.rFonts.set(qn('w:eastAsia'), "Microsoft YaHei")

def bullet(text, level=0):
    p = doc.add_paragraph(style='List Bullet')
    r = p.add_run(text); set_cjk_run(r); r.font.size = Pt(10.5)
    if level: p.paragraph_format.left_indent = Cm(1.0 + 0.6*level)
    return p

def numbered(text):
    p = doc.add_paragraph(style='List Number')
    r = p.add_run(text); set_cjk_run(r); r.font.size = Pt(10.5)
    return p

def make_table(headers, rows, widths=None, header_bg="2D3E63"):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        run = hdr[i].paragraphs[0].add_run(h)
        run.bold = True; run.font.size = Pt(9.5); run.font.color.rgb = RGBColor(0xFF,0xFF,0xFF)
        set_cjk_run(run)
        tcPr = hdr[i]._tc.get_or_add_tcPr()
        shd = tcPr.makeelement(qn('w:shd'), {qn('w:val'):'clear', qn('w:fill'):header_bg})
        tcPr.append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(val))
            run.font.size = Pt(9.5); set_cjk_run(run)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    return t

