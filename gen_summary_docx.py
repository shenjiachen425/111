FONT = "Microsoft YaHei"


def set_font(run, name=FONT, size=None, bold=None, color=None):
    run.font.name = name
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts'); rpr.append(rfonts)
    for a in ('w:eastAsia', 'w:ascii', 'w:hAnsi'):
        rfonts.set(qn(a), name)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if color is not None:
        run.font.color.rgb = RGBColor(*color)


def H(doc, text, level=1):
    p = doc.add_heading(level=level)
    r = p.add_run(text); set_font(r, size=16 if level == 1 else 13 if level == 2 else 11.5, bold=True,
                                  color=(0x1f, 0x3a, 0x5f) if level <= 2 else (0x33, 0x33, 0x33))
    return p


def P(doc, text, size=10.5, bold=False, color=(0x33, 0x33, 0x33), align=None, space=4):
    p = doc.add_paragraph()
    r = p.add_run(text); set_font(r, size=size, bold=bold, color=color)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space)
    return p


def BULLET(doc, text, size=10.5, bold_lead=None):
    p = doc.add_paragraph(style='List Bullet')
    if bold_lead:
        r = p.add_run(bold_lead); set_font(r, size=size, bold=True, color=(0x44, 0x44, 0x44))
        r2 = p.add_run(text); set_font(r2, size=size)
    else:
        r = p.add_run(text); set_font(r, size=size)
    p.paragraph_format.space_after = Pt(2)
    return p


def table(doc, headers, rows, widths=None, fontsize=9.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Light Grid Accent 1'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ''
        r = c.paragraphs[0].add_run(h); set_font(r, size=fontsize, bold=True, color=(0xff, 0xff, 0xff))
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        tcPr = c._tc.get_or_add_tcPr()
        shd = OxmlElement('w:shd'); shd.set(qn('w:val'), 'clear'); shd.set(qn('w:fill'), '2D3E63')
        tcPr.append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            r = cells[i].paragraphs[0].add_run(str(val)); set_font(r, size=fontsize)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Inches(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


